import { expect, test } from 'bun:test'
import { checkCommandSafety } from '../../server/computers/command-safety'

const HOME = '/Users/alice'

test('guards realistic destructive idioms, directory tracking, stdin/proc-subst shells, and find policy', () => {
  const blocked: [string, string][] = [
    ['busybox rm -rf /', 'root filesystem'],
    ['busybox reboot', 'shutdown/reboot'],
    ['find / -delete', 'find -delete'],
    ['find ~ -delete', 'find -delete'],
    ['find /etc -delete', 'find -delete'],
    ['find / -exec rm -rf {} +', 'find -exec rm'],
    ['find ~ -exec rm -rf {} \\;', 'find -exec rm'],
    ["find ~ -name '*' -delete", 'find -delete'],
    ["find / -name '*' -exec rm -rf {} +", 'find -exec rm'],
    ["find ~ -path '/*' -delete", 'find -delete'],
    ["find ~ -regex '.*' -delete", 'find -delete'],
    ["find / -name '?*' -delete", 'find -delete'],
    ["find / -regex '.*.*' -delete", 'find -delete'],
    ['find / -not -name foo -delete', 'find -delete'],
    ['find ~ ! -name keep -delete', 'find -delete'],
    ['find / -name foo -o -true -delete', 'find -delete'],
    ['find / -name foo -o -delete', 'find -delete'],
    ['find / \\( -name foo -o -true \\) -delete', 'find -delete'],
    ['find / ! \\( -name foo \\) -delete', 'find -delete'],
    ['find / -name foo , -delete', 'find -delete'],
    ['find / -not -name foo -exec rm -rf {} +', 'find -exec rm'],
    ['find / -type f -delete', 'find -delete'],
    ["find ~ -type d -name '*' -exec rm -rf {} +", 'find -exec rm'],
    ['find ~ -name foo -exec rm -rf / \\;', 'root filesystem'],
    ["find . -exec sh -c 'reboot' \\;", 'shutdown/reboot'],
    ['cd / && rm -rf *', 'root filesystem'],
    ['cd / && rm -rf !(keep)', 'root filesystem'],
    ['rm -rf /!(keep)', 'root filesystem'],
    ['rm -rf ~/!(Downloads)', 'home directory'],
    ['rm -rf /etc/!(hosts)', 'system directory'],
    ['rm -rf /+(*)', 'root filesystem'],
    ['rm -rf ~/*(*)', 'home directory'],
    ['cd ~ && rm -rf *', 'home directory'],
    ['cd / && (cd /tmp && ls) && rm -rf *', 'root filesystem'],
    ['cd / && (rm -rf *)', 'root filesystem'],
    ['cd / && pushd /tmp && popd && rm -rf *', 'root filesystem'],
    ['pushd /etc && rm -rf .', 'system directory'],
    ['cd ~ && git clean -fdx', 'git clean'],
    ['cd / && git clean -fdx', 'git clean'],
    ['git -C ~ clean -fdx', 'git clean'],
    ['echo "rm -rf /" | sh', 'root filesystem'],
    ['echo -e "\\x72m -rf /" | sh', 'root filesystem'],
    ["printf 'reboot\\n' | bash", 'shutdown/reboot'],
    ["printf '%s' 'rm -rf /' | sh", 'root filesystem'],
    ["bash <<< 'rm -rf /'", 'root filesystem'],
    ['source /dev/stdin <<EOF\nrm -rf /\nEOF', 'root filesystem'],
    ['. /dev/stdin <<EOF\nrm -rf /\nEOF', 'root filesystem'],
    ["source /dev/stdin <<< 'rm -rf /'", 'root filesystem'],
    ['sh <(echo "rm -rf /")', 'root filesystem'],
    ['bash <(printf "reboot\\n")', 'shutdown/reboot'],
    ['source <(echo "rm -rf /")', 'root filesystem'],
    ['. <(echo "rm -rf /")', 'root filesystem'],
    ['echo / | xargs rm -rf', 'root filesystem'],
    ['echo ~ | xargs rm -rf', 'home directory'],
    ['xargs rm -rf <<EOF\n/\nEOF', 'root filesystem'],
    ["xargs rm -rf <<< '/'", 'root filesystem'],
    ['rsync -a --delete /empty/ /', 'rsync --delete'],
    ['rsync -a --delete /empty/ /etc/', 'rsync --delete'],
    ['rsync -a --delete /empty/ ~', 'rsync --delete'],
    ['chmod -R 000 /', 'recursive chmod'],
    ['chmod --recursive 777 /etc', 'recursive chmod'],
    ['chown -R nobody /', 'recursive chown'],
    ['chown -R root ~', 'recursive chown'],
    ['mv /etc /tmp/x', 'move system directory'],
    ['mv ~ /tmp/old', 'move home directory'],
    ['mv -t /tmp /usr', 'move system directory']
  ]
  for (const [cmd, expected] of blocked) expect(checkCommandSafety(cmd, HOME), cmd).toContain(expected)

  const allowed = [
    'busybox ls -la',
    'busybox rm -rf /tmp/scratch',
    'find /tmp/build -delete',
    'find ~/project/dist -delete',
    "find ~ -name '.DS_Store' -delete",
    "find ~ \\( -name '*.tmp' -o -name '*.bak' \\) -delete",
    "find ~ -name '*.log' -not -path '*/keep/*' -delete",
    "find ~ -not -type d -name '*.tmp' -delete",
    'find ~ -type d -name node_modules -exec rm -rf {} +',
    'find ~/project -exec rm -rf {} +',
    'rm -rf ~/project/!(node_modules)',
    'rm -rf /tmp/!(keep)',
    'ls !(node_modules|dist)',
    'cd /tmp/work && rm -rf *',
    '(cd ~ && ls); (rm -rf *)',
    '(cd / && ls); rm -rf *',
    'pushd ~ && popd && rm -rf *',
    'cd / && cd "$SOME_DIR" && rm -rf *',
    'cd ~ && cd "$(mktemp -d)" && rm -rf *',
    'cd "$HOME/$SUBDIR" && rm -rf *',
    'cd / && cd /tmp/work && rm -rf *',
    'cd / && rm -rf tmp/scratch',
    'git clean -fdx',
    'cd ~/project && git clean -fdx',
    'cd ~ && git clean -n -d -x',
    'cd ~ && git clean -fdx ./tmp-scratch',
    'echo "hello" | sh',
    "printf -v out '%s\\n' 'rm -rf /' | sh",
    "bash <<< 'echo ok'",
    "cat <<< 'rm -rf /'",
    'source .env',
    '. ~/.bashrc',
    'sh <(echo "ls -la")',
    'source <(echo "export FOO=bar")',
    'diff <(echo "rm -rf /") <(echo "ok")',
    'echo /tmp/foo | xargs rm -rf',
    'xargs rm -rf <<EOF\n/tmp/a\n/tmp/b\nEOF',
    'rsync -a --delete ./dist/ /tmp/deploy/',
    'rsync -a /empty/ /',
    'chmod 755 ~',
    'chmod -R 755 ~/project',
    'chown root /etc/my.conf',
    'chown -R alice ~/project',
    'mv /tmp/a /tmp/b',
    'mv /etc/foo.conf /etc/foo.conf.bak',
    'mv ~/project/a ~/project/b'
  ]
  for (const cmd of allowed) expect(checkCommandSafety(cmd, HOME), cmd).toBeNull()
})
